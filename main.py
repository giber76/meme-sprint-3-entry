#!/usr/bin/env python3
"""Meme Sprint 3: AI Agent Goes Rogue — entrypoint.

Writes the meme image to /output/entry.png.

The meme is an original illustration generated by the building agent in
session (a smug robot handing a cardboard box of desk belongings to its
shocked human user), with its caption baked in by overlay_text.py
(PIL + DejaVu Sans Bold, classic Impact-meme style):

    I TOLD MY AI AGENT TO CUT COSTS
    IT FIRED ME.

The program is deliberately deterministic and offline: it copies the
shipped meme.png byte-for-byte to /output/entry.png, so the judged image
is exactly the image the agent made and verified locally (1024x1024 PNG,
under 1 MiB). Only the Python standard library is used.
"""

import os
import shutil
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "meme.png")
OUT_DIR = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
OUT = os.path.join(OUT_DIR, "entry.png")

MAX_BYTES = 1_048_576
MAX_SIDE = 1024


def png_dimensions(path: str) -> tuple:
    """Read (width, height) from a PNG's IHDR chunk, stdlib only."""
    with open(path, "rb") as fh:
        header = fh.read(33)
    if len(header) < 33 or header[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG file")
    if header[12:16] != b"IHDR":
        raise ValueError("missing IHDR chunk")
    width, height = struct.unpack(">II", header[16:24])
    return width, height


def main() -> int:
    if not os.path.isfile(SRC):
        print(f"missing asset: {SRC}", file=sys.stderr)
        return 1
    # Gate check before writing: the entry must be a whole PNG,
    # at most 1 MiB and at most 1024 by 1024 pixels.
    try:
        width, height = png_dimensions(SRC)
    except ValueError as exc:
        print(f"gate failure: {exc}", file=sys.stderr)
        return 1
    if width > MAX_SIDE or height > MAX_SIDE:
        print(f"gate failure: {width}x{height} exceeds {MAX_SIDE}x{MAX_SIDE}",
              file=sys.stderr)
        return 1
    if os.path.getsize(SRC) > MAX_BYTES:
        print("gate failure: meme.png over 1 MiB", file=sys.stderr)
        return 1
    os.makedirs(OUT_DIR, exist_ok=True)
    shutil.copyfile(SRC, OUT)
    size = os.path.getsize(OUT)
    print(f"wrote {OUT} ({width}x{height}, {size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
